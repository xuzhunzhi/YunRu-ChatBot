function prefRow(main, end, options = {}) {
  // `options.icon`：行首图标（一格里一堆开关时，图标是最快的区分手段）。
  // 来自 Miuix 官方图标库，跟侧栏是同一套图形。
  const lead = options.icon ? icon(options.icon, "pref-icon") : "";
  return `<div class="pref${options.extra || ""}">
    ${lead}
    <div class="pref-main">${main}</div>
    <div class="pref-end">${end}</div>
  </div>`;
}

function prefTitle(text, overridden) {
  // 面板覆盖过的项在主标题后面点一个小蓝点（原来左边有一道蓝条，配上表格很重）
  return `<div class="pref-title">${esc(text)}${
    overridden ? '<span class="pref-dot" title="面板改过这一项"></span>' : ""}</div>`;
}

function prefSummary(field, hint) {
  const bits = [];
  if (hint || field.note) bits.push(esc(hint || field.note));
  // 真实键名放最后一行小字：平时不碍眼，要核对时找得到。
  bits.push(`<code>${esc(field.key)}</code>`);
  if (field.applies === "restart") bits.push("改完需重启");
  return `<div class="pref-summary">${bits.join(" · ")}</div>`;
}

function settingsRow(field, label, hint, flags, glyph) {
  const key = field.key;
  const head = prefTitle(label, field.overridden) + prefSummary(field, hint);
  if (field.kind === "bool") {
    const on = flags[key] !== undefined ? Boolean(flags[key]) : field.current === "开";
    // `需重启` 的开关用主色**降饱和**来表示"改了要重启才生效"，但勾选状态必须
    // 如实反映当前值——**不能**为了好看把它画成未选中：保存时会把 checked
    // 上报成 "0"，那就等于顺手把自动审批关掉了（差点这么写）。
    const pending = field.applies !== "live";
    return prefRow(head,
      `<input class="switch${pending && on ? " is-pending" : ""}" type="checkbox"
        data-key="${esc(key)}" data-flag="1"${on ? " checked" : ""} aria-label="${esc(label)}">`,
      { icon: glyph });
  }
  if (key === "provider") {
    const options = (state.last.providers || []).map((p) =>
      `<option value="${esc(p.value)}"${p.value === field.current ? " selected" : ""}>${
        esc(p.label)}</option>`).join("");
    return prefRow(head, `<select data-key="${esc(key)}" aria-label="${esc(label)}">${options}</select>`,
      { icon: glyph });
  }
  // 凭据只给掩码、绝不回填明文；所以这里是"留空 = 不改"的占位符，
  // 想清掉这一项要用旁边那个按钮（见保存逻辑里 `dataset.clear`）。
  const type = field.kind === "secret" ? "password" : "text";
  const input = `<input data-key="${esc(key)}" type="${type}" placeholder="${
    esc(field.current || "未设置")}" aria-label="${esc(label)}">`;
  const clear = field.overridden
    ? `<button type="button" class="pref-clear" data-key="${esc(key)}"
         title="把这一项从面板覆盖层里去掉">清除</button>`
    : "";
  return prefRow(head, input + clear, { icon: glyph });
}

function settingsGroup(spec, byKey) {
  const rows = spec.items.map(([key, label, hint, glyph]) => {
    const field = byKey[key];
    return field ? settingsRow(field, label, hint, state.last.flags || {}, glyph) : "";
  }).join("");
  return rows ? `<div class="pref-group"><div class="pref-group-title">${
    esc(spec.title)}</div><div class="pref-list">${rows}</div></div>` : "";
}

