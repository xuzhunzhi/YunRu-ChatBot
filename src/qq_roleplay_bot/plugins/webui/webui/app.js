async function api(path, options = {}) {
  const headers = { "Content-Type": "application/json" };
  if (state.token) headers.Authorization = "Bearer " + state.token;
  const csrf = (document.cookie.match(/(?:^|;\s*)csrf=([^;]+)/) || [])[1];
  if (csrf) headers["X-CSRF-Token"] = decodeURIComponent(csrf);
  const response = await fetch(path, {
    method: options.method || "GET",
    headers,
    credentials: "same-origin",
    body: options.body ? JSON.stringify(options.body) : undefined,
  });
  const text = await response.text();
  let data = {};
  try { data = JSON.parse(text); } catch (e) { data = { raw: text }; }
  if (!response.ok || data.ok === false) {
    const detail = data.detail || data.error || ("HTTP " + response.status);
    throw new Error(detail);
  }
  return data.data !== undefined ? data.data : data;
}

function confirmWrite(question) {
  // HyperOS 那种居中卡片式确认，而不是浏览器原生的 confirm()——原生弹窗样式
  // 跟面板完全不是一套语言，而且会被"阻止此页面创建更多对话框"悄悄吞掉。
  return new Promise((resolve) => {
    const scrim = document.createElement("div");
    scrim.className = "scrim";
    scrim.innerHTML = `
      <div class="dialog" role="dialog" aria-modal="true">
        <h3>确认操作</h3>
        <p>${esc(question)}</p>
        <div class="actions">
          <button type="button" data-answer="no">取消</button>
          <button type="button" class="danger" data-answer="yes">确定</button>
        </div>
      </div>`;
    const finish = (answer) => {
      scrim.remove();
      document.removeEventListener("keydown", onKey);
      resolve(answer);
    };
    const onKey = (event) => {
      if (event.key === "Escape") finish(false);
      if (event.key === "Enter") finish(true);
    };
    scrim.addEventListener("click", (event) => {
      const target = event.target;
      if (target === scrim) { finish(false); return; }
      const button = target.closest("[data-answer]");
      if (button) finish(button.dataset.answer === "yes");
    });
    document.addEventListener("keydown", onKey);
    document.body.appendChild(scrim);
    const yes = scrim.querySelector('[data-answer="yes"]');
    if (yes) yes.focus();
  });
}

async function write(path, body, question) {
  if (!(await confirmWrite(question))) return null;
  try {
    const data = await api(path, { method: "POST", body: { ...body, confirm: true } });
    showError("");
    return data;
  } catch (error) {
    showError("操作失败：" + error.message);
    return null;
  }
}

