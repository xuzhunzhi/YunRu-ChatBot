/* 页脚那行只读读数：**用来问真值的**——手机上打开一眼就知道 DPR 是多少、
 * 落在响应式哪一档。断点该取多少，按这个数调，不靠赌机型。
 *
 * ⚠️ **档位不去猜断点**（2026-10-04 审查指出）：原来这里硬编码了 `699`/`1100`，
 * 和 `app.css` 的 `@media` 成了**两个真相源**——改 CSS 就会让读数漂移。
 * 现在改成**量真实布局**：内容栏看不看得见、左栏的 `flex-basis` 是多少，
 * 都是 CSS 自己算出来的结果，CSS 改了读数自动跟着变。
 */
function showViewport() {
  const box = $("viewport");
  if (!box) return;
  const width = window.innerWidth || 0;
  const height = window.innerHeight || 0;
  const dpr = window.devicePixelRatio || 1;
  let band = "未知";
  const rail = document.querySelector(".rail");
  const content = document.querySelector(".content");
  if (rail && window.getComputedStyle) {
    const style = window.getComputedStyle(rail);
    const contentHidden = content
      && window.getComputedStyle(content).display === "none";
    const basis = style.flexBasis || "";
    if (contentHidden) band = "窄屏（只留左栏）";
    else if (basis === "240px") band = "宽屏（左栏定宽）";
    else if (basis && basis !== "auto") band = `中等（左栏 ${basis}）`;
  }
  box.textContent = `视口 ${width}×${height} · DPR ${dpr} · ${band}`;
}

