/* ---------- 事件绑定（事件委托，避免每次重绘都重绑） ---------- */

function bind() {
  $("view").addEventListener("click", async (event) => {
    const target = event.target;
    if (!(target instanceof HTMLElement)) return;
    const act = (name, handler) => {
      if (target.classList.contains(name)) { handler(target); return true; }
      return false;
    };
    if (act("group-off", async (el) => {
      const done = await write("/api/groups", { group_id: el.dataset.id, enabled: false },
        "关闭群 " + el.dataset.id + " 的对话？");
      if (done) render();
    })) return;
    // --- 从左栏底部搬过来的两样（2026-10-06）--------------------------------
    // 它们的 DOM 长在页面内容里（调参页 / 账号页），所以走委托、不走 `init()`。
    if (target.id === "panel-theme") {
      // 主题是**这台浏览器**的偏好（localStorage），不进 data/、也不进覆盖层——
      // 所以它不走 `/api/settings` 那套"保存改动"，点一下立即生效。
      const next = target.checked ? "dark" : "light";
      localStorage.setItem("yunru_panel_theme", next);
      applyTheme(next);
      return;
    }
    if (target.id === "signout") {
      localStorage.removeItem("yunru_panel_token");
      state.token = "";
      lock(true);            // 回到登录页（面板本身照旧在跑）
      return;
    }
    if (target.id === "group-on") {
      const done = await write("/api/groups", { group_id: $("group-add").value, enabled: true },
        "开启这个群的对话？");
      if (done) render();
      return;
    }
    if (act("clear-session", async (el) => {
      const done = await write("/api/session/clear", { session_id: el.dataset.id },
        "清空会话 " + el.dataset.id + "？");
      if (done) render();
    })) return;
    if (act("do-action", async (el) => {
      const row = el.closest("tr");
      const body = {
        group: el.dataset.group,
        kind: el.dataset.kind,
        group_id: (row.querySelector(".a-group") || {}).value || "",
        target_id: (row.querySelector(".a-target") || {}).value || "",
        text: (row.querySelector(".a-text") || {}).value || "",
        message_id: (row.querySelector(".a-msg") || {}).value || "",
      };
      const done = await write("/api/action", body, "执行 " + body.kind + "？");
      if (done) showError("结果：" + (done.message || ""));
    })) return;
    if (act("join-approve", async (el) => {
      const done = await write("/api/approval",
        { flag: el.dataset.flag, group_id: el.dataset.group, approve: true }, "通过这条入群申请？");
      if (done) render();
    })) return;
    if (act("join-reject", async (el) => {
      const done = await write("/api/approval",
        { flag: el.dataset.flag, group_id: el.dataset.group, approve: false },
        "拒绝这条入群申请？");
      if (done) render();
    })) return;
    if (target.id === "purge") {
      const ids = Array.from(document.querySelectorAll(".pick:checked")).map((box) => box.value);
      if (!ids.length) { showError("还没勾任何一条。"); return; }
      const done = await write("/api/memory/purge", { record_ids: ids, reason: "面板人工清理" },
        "删除勾选的 " + ids.length + " 条记忆？");
      if (done) render();
      return;
    }
    if (target.classList.contains("pref-clear")) {
      // 只是**标记**要清除这一项，真正的提交还在"保存改动"那一步
      // （避免点一下就写盘，也让人有机会反悔）。
      const box = document.querySelector(`[data-key="${target.dataset.key}"]`);
      if (box) {
        box.value = "";
        box.dataset.clear = "1";
        box.classList.add("is-clearing");
        target.disabled = true;
        target.textContent = "将清除";
      }
      return;
    }
    if (target.id === "save-settings") {
      const body = {};
      document.querySelectorAll("[data-key]").forEach((el) => {
        const raw = String(el.value || "").trim();
        if (el.dataset.clear === "1") {
          // "清除这一项"：显式送空串（落盘时等价于把它从覆盖层里拿掉）。
          // 密钥框**故意不回填明文**，所以光靠"留空"没法表达这个意图——
          // 没这个按钮的话"留空密钥表示清掉这一项"就是句空话。
          body[el.dataset.key] = "";
          return;
        }
        if (el.getAttribute("data-flag") === "1") {
          // 开关：复选框的 value 在选中/未选中时都是 "on"/"1"，
          // 真正的新值要从 checked 读，永远都要上报（关掉也是一种意图）。
          body[el.dataset.key] = el.checked ? "1" : "0";
          return;
        }
        if (el.tagName === "SELECT" || raw) body[el.dataset.key] = raw;
      });
      if (!Object.keys(body).length) { showError("没有要改的项。"); return; }
      const done = await write("/api/settings", body, "保存这些配置改动？");
      if (done) {
        const lines = Object.entries(done.applied || {})
          .map(([k, v]) => k + "：" + (v.applied === "live" ? "已生效" : v.applied === "restart_required" ? "需重启" : "被拒 " + (v.detail || "")));
        showError("改动结果\n" + lines.join("\n"));
        render();
      }
      return;
    }
    if (act("edit-prompt", async (el) => {
      const name = el.dataset.name;
      const all = await api("/api/prompts");
      const item = (all.prompts || []).find((p) => p.name === name);
      $("prompt-editor").innerHTML = `
        <div class="card-inline">
          <h2>编辑 ${esc(name)}</h2>
          <textarea id="prompt-text" class="tall">${esc(item ? item.text : "")}</textarea>
          <div class="row">
            <button id="prompt-save" data-name="${esc(name)}">保存</button>
            <button id="prompt-reset" data-name="${esc(name)}">恢复内置默认</button>
            <span class="hint" id="prompt-note"></span>
          </div>
        </div>`;
    })) return;
    if (target.id === "prompt-save") {
      const done = await write("/api/prompts", { action: "save", name: target.dataset.name,
        text: $("prompt-text").value }, "保存 " + target.dataset.name + " 这套 prompt？");
      if (done) render();
      return;
    }
    if (target.id === "prompt-reset") {
      const done = await write("/api/prompts", { action: "reset", name: target.dataset.name },
        "恢复 " + target.dataset.name + " 的内置默认？");
      if (done) render();
      return;
    }
    if (target.id === "kb-add") {
      const done = await write("/api/knowledge/operator", {
        action: "add", title: $("kb-title").value, content: $("kb-content").value,
      }, "新增这一块知识？");
      if (done) render();
      return;
    }
    if (act("del-chunk", async (el) => {
      const done = await write("/api/knowledge/operator", { action: "delete", id: el.dataset.id },
        "删除这一块？（上一版留在版本里，可回滚）");
      if (done) render();
    })) return;
    if (act("mem-status", (el) => {
      state.last.memoryStatus = el.dataset.status;
      render();
    })) return;
    if (target.id === "kb-search") {
      state.last.knowledgeQuery = $("kb-q").value;
      render();
      return;
    }
    if (target.id === "log-go") {
      state.last.logFeature = $("log-feature").value;
      render();
      return;
    }
    if (target.id === "aff-go") {
      const done = await write("/api/memory/affinity", {
        user_id: $("aff-user").value, axis: $("aff-axis").value, delta: Number($("aff-delta").value),
      }, "调整这个人的关系档位？");
      if (done) showError("现在是：" + JSON.stringify(done.values || {}));
      return;
    }
    if (target.id === "aff-reset") {
      const done = await write("/api/memory/affinity",
        { user_id: $("aff-user").value, reset: true }, "按回默认档？");
      if (done) showError(done.changed ? "已按回默认档。" : "本来就是默认档。");
      return;
    }
    if (target.id === "restart") {
      if (!confirmWrite("重启 bot？")) return;
      try {
        const data = await api("/api/control/restart", { method: "POST", body: { confirm: true } });
        showError(data.message || "正在重启。");
        setTimeout(() => render(), 4000);
      } catch (error) { showError("重启失败：" + error.message); }
      return;
    }
  });
}

