function mdInline(line, stash) {
  let text = String(line);
  // 行内代码**先摘出来占位**：代码里的 `**` 不是加粗——测试抓到过
  // `<code><b>不该变粗</b></code>` 这个错。
  if (stash) {
    text = text.replace(/`([^`]+)`/g, function (_all, code) {
      stash.push("<code>" + code + "</code>");
      return "\u0000I" + (stash.length - 1) + "\u0000";
    });
  }
  text = text
    .replace(/\*\*([^*]+)\*\*/g, "<b>$1</b>")
    .replace(/(^|[\s(])\*([^*\n]+)\*/g, "$1<i>$2</i>")
    .replace(/(^|[\s(])_([^_\n]+)_/g, "$1<i>$2</i>");
  if (stash) {
    text = text.replace(/\u0000I(\d+)\u0000/g, function (_all, index) {
      return stash[Number(index)];
    });
  }
  return text;
}

function mdToHtml(text, escFn) {
  // **不要写 `const esc = escFn || esc`**：局部 `const esc` 会遮蔽全局的 `esc()`，
  // 初始化时读它自己 → `ReferenceError: Cannot access 'esc' before initialization`，
  // 整个知识库页直接打不开（2026-10-01 截图时抓到）。渲染器按参数收 esc，别兜底。
  if (typeof escFn !== "function") throw new Error("mdToHtml 需要 esc 函数");
  let source = escFn(String(text || "")).replace(/\r\n?/g, "\n");
  const blocks = [];
  const inlineStash = [];
  // 围栏代码块：先摘出来占位，免得里面的内容被后面的行内规则改坏
  source = source.replace(/```([\s\S]*?)```/g, function (_all, body) {
    blocks.push('<pre class="md-code">' + body.replace(/^\n/, "") + "</pre>");
    return "\u0000BLOCK" + (blocks.length - 1) + "\u0000";
  });

  const lines = source.split("\n");
  const out = [];
  let list = null;      // "ul" | "ol" | null
  let table = null;     // 累积中的表格行

  function closeList() {
    if (list) { out.push("</" + list + ">"); list = null; }
  }
  function closeTable() {
    if (table && table.length) {
      const cellsOf = function (line) {
        return line.replace(/^\s*\|/, "").replace(/\|\s*$/, "")
          .split("|").map(function (cell) { return mdInline(cell.trim(), inlineStash); });
      };
      const head = cellsOf(table[0]);
      const body = table.slice(1).map(cellsOf);
      out.push(
        '<table class="md-table"><thead><tr>'
        + head.map(function (c) { return "<th>" + c + "</th>"; }).join("")
        + "</tr></thead><tbody>"
        + body.map(function (row) {
          return "<tr>" + row.map(function (c) { return "<td>" + c + "</td>"; }).join("") + "</tr>";
        }).join("")
        + "</tbody></table>",
      );
    }
    table = null;
  }

  for (let index = 0; index < lines.length; index += 1) {
    const line = lines[index];
    const placeholder = line.match(/^\u0000BLOCK(\d+)\u0000$/);
    if (placeholder) {
      closeList(); closeTable();
      out.push(blocks[Number(placeholder[1])]);
      continue;
    }
    if (!line.trim()) { closeList(); closeTable(); continue; }
    if (/^\s*\|.*\|\s*$/.test(line)) {
      if (table === null) { closeList(); table = [line]; }
      else if (!/^\s*\|[\s:|-]+\|\s*$/.test(line)) { table.push(line); }
      continue;
    }
    closeTable();
    const heading = line.match(/^(#{1,6})\s+(.*)$/);
    if (heading) {
      closeList();
      const level = Math.min(6, heading[1].length + 2);   // 面板里 h1 太抢，整体降两级
      out.push("<h" + level + ' class="md-h">' + mdInline(heading[2], inlineStash) + "</h" + level + ">");
      continue;
    }
    if (/^\s*([-*_])\1{2,}\s*$/.test(line)) { closeList(); out.push("<hr>"); continue; }
    const quote = line.match(/^\s*&gt;\s?(.*)$/);
    if (quote) { closeList(); out.push("<blockquote>" + mdInline(quote[1], inlineStash) + "</blockquote>"); continue; }
    const bullet = line.match(/^\s*[-*+]\s+(.*)$/);
    if (bullet) {
      if (list !== "ul") { closeList(); out.push("<ul>"); list = "ul"; }
      out.push("<li>" + mdInline(bullet[1], inlineStash) + "</li>");
      continue;
    }
    const numbered = line.match(/^\s*\d+[.)]\s+(.*)$/);
    if (numbered) {
      if (list !== "ol") { closeList(); out.push("<ol>"); list = "ol"; }
      out.push("<li>" + mdInline(numbered[1], inlineStash) + "</li>");
      continue;
    }
    closeList();
    out.push("<p>" + mdInline(line, inlineStash) + "</p>");
  }
  closeList(); closeTable();
  return out.join("");
}
