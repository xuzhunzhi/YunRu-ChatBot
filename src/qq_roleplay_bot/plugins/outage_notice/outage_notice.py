"""掉线通知的**正文**与"被叫一次"要做的事。

## 措辞（用户前后改过三次，最后两次都在 2026-10-11）

这封信的收件人是**操作者**（同 `MAIL_REPORT_TO`），不是"云茹写给主人"的那种信。

先是把措辞交给我们（*"怎么触发，yunru 怎么说话就你自己看着办了"*），当时选了
**第三人称的运维腔**（"她收不到群里的消息"）；用户看过线上那封真信之后改口
（原话：*"这里，我认为可以用yunru语气"*）——**看得懂和像她说话不冲突**。
所以现在的正文是**她那口气**：第一人称、短句、直说，但**仍然是固定模板、不调模型**。

保留的骨架：第一行"我这边断了。"（一眼认出是什么事）+ **一个原样的时刻**
（`2026-10-06 21:37:12（+0800）`，操作者不必自己换算时区）。换掉的是人称与语气。正文：

    我这边断了。

    QQ 那头连不上，群里的消息我收不到，我说的话也发不出去。能不能把 NapCat 重开一次？
    断线期间漏掉的消息补不回来，我只能从重开之后重新开始听。

    断的时候是 2026-10-06 21:37:12（+0800）。

**2026-10-11 第二次改口**（原话：*"就不能把方括号丢掉吗，从yunru角度，这是求助邮件不是通知"*）：
`【时间】【怎么回事】【怎么办】` 那套小标题全去掉了。用户的判断是**信的性质**——
这不是一份发给运维的通知，是**她自己在求人帮忙**："能不能把 NapCat 重开一次？"
通知腔才需要小标题；一个人求人帮忙时不会写【怎么回事】。所以：人称是"我"，
问句是问句，时刻夹在句子中间（"断的时候是 …"），三段小标题一个不留。
（`【】` 这两个字符现在整个模板里都不出现——有一条判据钉着。）

**第三次改口**（原话：*"这封是自动发的不留，不用交代机制"*）：结尾那句
"—— 这封是自动发的：一段断线只发一封，恢复了不另发。"也删了。那行是**机器在声明
自己不是人**：一个人求人帮忙，不会在自己消息末尾附"本条为系统自动发出"。
"一段断线只发一封"是核心的行为（同一段掉线里不会再叫她第二次，见本包说明），
不需要她来交代；操作者也不靠她这行字才知道这是自动的。

## 为什么还是固定模板（两个理由）

1. **可靠**：这封信是"出事时唯一出得去的那一封"，不能依赖模型可用性——用户要的是
   "告警要确定、要便宜"（`tests/test_outage_notice.py` 有一条专门钉住"没有模型调用"）。
2. **守边界**：用她的语气 ≠ 让插件去拿她的人格。这份措辞是**手写的定稿**：
   不读人格文件、不拼她的系统提示、不碰对话那条路（`AGENTS.md`：插件不许干涉对话）。

## 为什么不讲机制词

`AGENTS.md` §2.2 那张表（`检查` / `触发` / `调用` / `协议` / `提示词` / `上下文` /
`记忆库` / `Stage`）是给**会流进她本人 prompt 的文本**定的。这封信不进 prompt，
但同一条道理在这里更硬：收件人读了要**马上知道做什么**，而"用她的口吻讲机制词"
只会让这封告警看不懂。所以：**直说**。测试里有一条专门扫这张表——她那口气里也不许混进来。

（"一段断线只发一封、恢复不另发"是**核心的行为**，不靠正文交代——见下面第三次改口。）

## "被叫一次"要做的事，就是发一封信

**这里没有"这一段断线通知过没有"的状态**——那是核心的活（见包的说明第 1 条）。
本模块被叫一次就发一封；同一段断线里核心不会再叫第二次。
"""

from __future__ import annotations

import logging
import time

logger = logging.getLogger(__name__)

#: 邮件主题。**固定**，只由时间区分（邮箱里按主题就能一眼认出这是告警）。
SUBJECT = "云茹断线了"

#: 正文模板。时刻占位，其余固定。
#: **这是手写的定稿、用她那口气**（2026-10-11 用户："我认为可以用yunru语气"，
#: 随后又："就不能把方括号丢掉吗，从yunru角度，这是求助邮件不是通知"——
#: 方括号那套小标题全去掉，改成她自己在求人帮忙；再随后："这封是自动发的不留，不用交代机制"——
#: 结尾那句"这封是自动发的"也删了，模板里不留任何机制交代）——
#: 不是模型生成的：插件不读人格、不拼她的系统提示（见模块说明那两个理由）。
NOTICE_TEMPLATE = (
    "我这边断了。\n"
    "\n"
    "QQ 那头连不上，群里的消息我收不到，我说的话也发不出去。"
    "能不能把 NapCat 重开一次？断线期间漏掉的消息补不回来，"
    "我只能从重开之后重新开始听。\n"
    "\n"
    "断的时候是 {moment}。"
)

#: 时刻的格式（本地时间 + UTC 偏移，操作者不必再自己换算）。
MOMENT_FORMAT = "%Y-%m-%d %H:%M:%S"


def format_moment(when: float | None = None) -> str:
    """把时刻写成"本地时间（±HH:MM）"。`when` 缺省是此刻。

    为什么带偏移：这台机器与读信的人可能不在一个时区，而"什么时候断的"是这封信
    最要紧的一条信息——只有裸时刻的话，对方每读一次都要自己推算。
    """

    local = time.localtime(time.time() if when is None else when)
    return time.strftime(MOMENT_FORMAT, local) + time.strftime("（%z）", local)


def build_notice(when: float | None = None) -> tuple[str, str]:
    """回 `(主题, 正文)`。**纯函数**：不碰网络、不碰注册表、不调模型。"""

    return SUBJECT, NOTICE_TEMPLATE.format(moment=format_moment(when))


async def notice_on_disconnect(send, when: float | None = None) -> bool:
    """掉线那一次被叫：发一封告警。返回"发出去了没有"。

    `send` 是 **mail 插件放上来的那个函数**（`(subject, body) -> await`，
    见 `plugins.MailSeams`）——本模块不知道它背后是哪个模块、哪个 CLI、发给谁。

    ## 失败只记一笔（用户要求 + `AGENTS.md` §2.1）

    **不许把机器人搞崩**：发不出去（没网、CLI 没装、凭据过期、对面退信）只在这里
    记一行 `outage_notice_send_failed`，然后返回 `False`。
    为什么**不再往上抛**：这一步的调用方是核心的广播侧
    （`runtime._DisconnectNotifier._broadcast`），它兜住异常、记一行
    `disconnect_receiver_failed`，**但它区分不了**"发信失败"与"这个插件有 bug"。
    在这里就地记下**具体是哪件事失败**，那行日志才有排障价值；
    而"不崩"这条判据不依赖调用方——本函数自己就保证不抛。
    `KeyboardInterrupt` / `SystemExit` 不属于"发信失败"，照旧上抛。
    """

    subject, body = build_notice(when)
    try:
        await send(subject, body)
    except Exception as exc:  # noqa: BLE001 - 发信失败的代价只能是一行日志
        logger.warning("outage_notice_send_failed error=%s", type(exc).__name__,
                       exc_info=True)
        return False
    logger.info("outage_notice_sent subject=%s", subject)
    return True
