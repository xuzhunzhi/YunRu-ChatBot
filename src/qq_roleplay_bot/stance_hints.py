"""这一轮有人拿一个工具式的称呼在叫她时，往易变段递**一句话**（纯正则，0 次模型调用）。

## 由来（2026-10-20 生产日志实测，群 `908696203`）

    04:32:48 Echokovo：bot你帮我看看 我睡了
             她：专利这事得你自己去翻，我不替他查。
    04:33:51 Echokovo：bot你敢不敢总结我们刚才的对话
             她：这有什么不敢的。从…卡在"热重建怎么做"上没了下文。

两次有人用 `bot` 称呼她，**她两次都顺着接了**——等于默认了这个称呼。用户口径：
**不接这个称呼，但也不装没听见**（可以反问 / 把话头拨回去，或者只回正题、态度冷一点）。

## 为什么不在人格正文里写（AGENTS §2.2）

人格是常驻的、每一轮都在。往那里写一句"有人叫你这个称呼你不接"，等于**每轮提醒她
有这么一个身份**——那正是 §2.2 要防的（prompt 里的措辞会被角色吸收）。
所以判据落在代码里，只在**这一轮真的有人这么叫她**时才递一行；而且那一行
**一个字都不提那个称呼**（连那三个字母都不写，见 `TOOL_VOCATIVE_NOTE`）。

## 为什么是纯正则，而不是再问一次模型

- 它只影响措辞，不值得为它多一腿模型调用；
- **判定那条路一个字都不许受影响**（用户口径："不要影响判定"）。判定有它自己的
  agent 与 `guard`（"你是不是机器人"那类打探由判定的 `PROBE` 压掉这一轮），
  这里只在**回复材料**里加一句，判定根本看不到它；
- 判据长什么样一眼能读、误伤能数、要改只改这一份正则（不是散在 prompt 里的一段话）。

## 判据要保守（用户口径"判据要保守"，2026-10-20）

群里天天在聊技术："这个 bot""部署了一个机器人""大模型 / AI 做…"——这些**一个都不许命中**，
误伤就是把每一轮都加一句。所以：

* `机器人` / `AI` / `人形` 是**普通话题词**：打头时只有紧跟「你」才算在叫她
  （"AI 能跑不等于该往里搭工夫"因此不命中）；打头紧跟逗号**不算**——那是话题句
  （"AI，这几年发展很快"）；
* `bot` 是英文工具名，打头时后面紧跟「你」或逗号/冒号/问叹号也算（"bot，帮我看看"）；
  **只认 `bot` 这一个词**，"robot"/"verifybot"/"maibot" 由左右两侧的字母边界排掉；
* 句中/反问那一组都要「你」就贴在那个词上（"你个bot""你是机器人吧"）——
  单纯在聊"机器人吧""这个机器人"不算，"你说它是机器人吧""你看那个机器人吧"也不算；
* 光一个"机器人吧 / bot 吧"打头也算，但**整条消息必须就这么长**——带后半句
  （"机器人吧，我看挺贵的"）那是话题标记；
* "你是不是机器人"这种**质问**不归这里：判定那条 `guard=PROBE` 已经压掉那一轮，
  这里再加一句就变成两头都在管同一件事。

## 什么时候能改回去（§7.1-4）

用户口径变了、或者实测发现这一行**反而让她更在意那个称呼**（那说明落点是错的：
说明"提一句"本身就是提醒）——那时应当**撤掉这一行**，不是往上面再加话。
"""
from __future__ import annotations

import re

#: 三家"称呼"的写法。`bot` 与 `AI` 要带**字母边界**：不然 `robot`、`verifybot`、
#: `maibot`、`email`、`detail` 里的那一截都会被当成在叫她（这是这段正则最容易被
#: 想当然写错的地方）。
_BOT = r"(?<![A-Za-z])bot(?![A-Za-z])"
_AI = r"(?<![A-Za-z])ai(?![A-Za-z])"
_ROBOT = r"机器人"
_HUMAN = r"人形"

_TOOL = rf"(?:{_BOT}|{_ROBOT}|{_HUMAN}|{_AI})"

#: **称呼打头**（在整条消息的开头；不认句中换行后的行首——`^` 没有 `re.M`）。
#:
#: 为什么 `机器人`/`AI` 打头时只认紧跟「你」、`bot` 打头才认标点：`机器人` 与 `AI`
#: 是**普通话题词**，"AI，这几年…""机器人，现在能做到什么程度"在技术群里很常见；
#: 而 `bot` 在这个群里是个工具名，打头就是叫它（实测 69 条含 `bot` 的消息里，
#: 只有那两条真是在叫她，两条都是 `bot` + `你`）。
_LEADING = tuple(re.compile(pattern, re.IGNORECASE) for pattern in (
    rf"^{_TOOL}\s*你",
    rf"^{_BOT}\s*[，,：:、!！?？~～]",
    rf"^(?:{_BOT}|{_ROBOT})\s*$",
    # 打头就是反问："机器人是吧"——整条消息只有这一问，叫的是她。
    rf"^(?:{_BOT}|{_ROBOT}|{_AI})\s*(?:是吧|对不对|对吧)",
    # 光一个"机器人吧"也算，但**必须整条消息就这么长**：带上后半句
    # （"机器人吧，我看挺贵的"）那是话题标记，不是在叫她。
    rf"^(?:{_BOT}|{_ROBOT})\s*吧\s*[?？!！。.~～]*$",
    r"^不是真人吧\s*[?？!！。.~～]*$",
))

#: **夹在句中**：这几条的「你」是模式自带的，所以不需要再判一次。
#:
#: 为什么「你个」里的那个 `个` 是**必须**的（2026-10-20 实测踩到的误伤）：
#: 真实日志里有一句「你可以试着和你ai说一声」——那是"你（的）AI"，不是在叫她。
#: 同理 "你这些AI" 是"你这些 AI 项目"的写法（"你们这些"才是冲着人说的），所以
#: `这些` 前面也必须带 `们`。
_EMBEDDED = tuple(re.compile(pattern, re.IGNORECASE) for pattern in (
    rf"你\s*个\s*{_TOOL}",              # 你个bot / 你个机器人 / 你个 AI
    rf"叫\s*你\s*个?\s*(?:{_BOT}|{_ROBOT})",   # 叫你个机器人 / 叫你机器人
    rf"你们\s*这些\s*{_TOOL}",          # 你们这些机器人 / 你们这些 bot
    rf"你(?:就)?是\s*个\s*{_TOOL}",     # 你就是个 bot / 你是个 AI
    rf"你(?:就)?是\s*(?:{_ROBOT}|{_HUMAN})",   # 你是机器人（不带"个"也说得出）
    r"你不是真人吧",
))

#: **反问式**（句中）：`你` 与那个词之间只许夹"就/真/是/个/一个"这几个字。
#:
#: 为什么不用"整条消息里有「你」+ 随便哪儿的「robot 吧」"：那样
#: "你说它是机器人吧""你看那个机器人吧"都会命中——那是在聊别人家的东西。
#: 紧挨着写之后，"你是机器人吧""你就是个机器人吧"命中，上面那两种不命中。
_REFLEXIVE = tuple(re.compile(pattern, re.IGNORECASE) for pattern in (
    rf"你(?:就|真)?(?:是)?\s*(?:个|一个|一只?)?\s*{_TOOL}\s*(?:是吧|对不对|对吧|吧)",
    r"你(?:就)?不是\s*(?:个|一个)?\s*真人吧",
))

#: 递给她的那一行。用户 2026-10-20 给了口径（"不接那个称呼，但也不装没听见"），
#: 第一版逐字用了交底里那句"有人拿一个不客气的称呼在叫你"；2026-10-20 当天改成现在这版，
#: 理由是**那句话本身在宣告"刚刚发生了一次身份称呼"**——正是 AGENTS §2.2 想避开的那类提醒，
#: 只是剂量小。现在只说"他这话不是在问事"，不再描述"有人这么叫你"。
#:
#: 三条硬约束，测试逐个钉着（`tests/test_stance_hints.py`）：
#: ① 不提那个称呼（`bot` / `机器人` / `AI` / `程序` 一个都不许有）——提它等于每轮提醒；
#: ② 不许出现机制词（AGENTS §2.2：检查 / 触发 / 调用 / 协议 / 提示词 / 上下文 / 记忆库 / Stage）；
#: ③ "不接"与"别装没听见"两半都在——少哪一半都不是用户要的那个分寸。
#: 什么时候能改回去：如果落地后发现她**反复否认/承认身份**（而不是把话头拨回去），
#: 说明这一行仍然在提醒她那个称呼，那时该撤掉整行，而不是再改措辞。
TOOL_VOCATIVE_NOTE = (
    "他刚才那句不是在问事。别顺着他的叫法，也别解释；"
    "别当没听见——把话头拨回去，或者只回正题。\n"
)


def looks_like_tool_vocative(text: str) -> bool:
    """这一条消息是不是**在拿工具式的称呼叫她**（纯字符串判断，0 次模型调用）。

    只该喂**这一轮新到的那条消息的正文**：判定过的历史里出现过这种称呼不算
    （用户口径："只对这一轮新到的消息正文判断，历史不算"）——历史是已经过去的
    对话，每轮都拿它再判一次等于每轮都加一句，那正是要避免的。
    """

    body = str(text or "").strip()
    if not body:
        return False
    if any(pattern.search(body) for pattern in _LEADING):
        return True
    if any(pattern.search(body) for pattern in _EMBEDDED):
        return True
    if any(pattern.search(body) for pattern in _REFLEXIVE):
        return True
    return False
