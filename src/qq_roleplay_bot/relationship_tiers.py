def clamp_likes(value: int) -> int:
    """把好感夹回刻度内。越界值一律夹回，**不报错**（读库拿到脏值时也要能说话）。"""

    return max(LIKES_MIN, min(LIKES_MAX, int(value)))


def clamp_guard(value: int) -> int:
    """把防备夹回刻度内。"""

    return max(GUARD_MIN, min(GUARD_MAX, int(value)))


def _lookup(tiers: tuple[Tier, ...], value: int) -> Tier:
    for tier in tiers:
        low, high = tier.span
        if low <= value <= high:
            return tier
    # 走到这里说明表本身有洞（区间没盖满刻度）。夹过之后再查表不该发生，
    # 但宁可回落成端点档，也不要让"她跟这个人的关系"整段消失。
    return tiers[-1] if value < tiers[-1].span[0] else tiers[0]


def likes_tier(value: int) -> Tier:
    """好感档：`(档名, 文字, 区间)`。越界值先夹回 `-100..100`。"""

    return _lookup(LIKES_TIERS, clamp_likes(value))


def guard_tier(value: int) -> Tier:
    """防备档：`(档名, 文字, 区间)`。越界值先夹回 `-30..30`。"""

    return _lookup(GUARD_TIERS, clamp_guard(value))


def likes_index(value: int) -> int:
    """好感是第几档（0 = 最高档）。给"哪一档"这类机械映射用（例如回话前搁多久）。"""

    tier = likes_tier(value)
    return LIKES_TIERS.index(tier)


def guard_index(value: int) -> int:
    """防备是第几档（0 = 绷得最紧，6 = 完全不设防）。"""

    tier = guard_tier(value)
    return GUARD_TIERS.index(tier)


def likes_text(value: int) -> str:
    """`档名——那句话`。三处消费都直接用这个形状，别再各自拼一次。"""

    tier = likes_tier(value)
    return f"{tier.name}——{tier.text}"


def guard_text(value: int) -> str:
    """`档名——那句话`。"""

    tier = guard_tier(value)
    return f"{tier.name}——{tier.text}"
